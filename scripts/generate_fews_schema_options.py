#!/usr/bin/env python3
"""
Script to automatically generate FEWSSchemaOption enum from actual schema files.

This script scans the data/fews_schemas/fewsdocs_deltares_nl directory and generates
the FEWSSchemaOption enum with all available schema files.
"""

import re
from pathlib import Path
from typing import List, Dict


def scan_schema_directory(
    schema_dir: str = "../data/fews_schemas/fewsdocs_deltares_nl",
) -> Dict[str, List[str]]:
    """
    Scan the schema directory and organize schemas by category.

    Args:
        schema_dir: Schema directory path relative to scripts directory.

    Returns:
        Dict with category names as keys and lists of schema filenames as values
    """
    schema_path = Path(schema_dir)
    if not schema_path.exists():
        raise FileNotFoundError(f"Schema directory not found: {schema_dir}")

    schemas_by_category = {
        "main": [],
        "pi_schemas": [],
        "adapter_schemas": [],
        "kisters_schemas": [],
        "fp_schemas": [],
        "ea_schemas": [],
        "archive_schemas": [],
        "topology_editor_schemas": [],
    }

    # Scan main directory
    for xsd_file in schema_path.glob("*.xsd"):
        schemas_by_category["main"].append(xsd_file.name)

    # Scan subdirectories
    subdirs = {
        "pi-schemas": "pi_schemas",
        "adapter-schemas": "adapter_schemas",
        "kisters-schemas": "kisters_schemas",
        "fp-schemas": "fp_schemas",
        "ea-schemas": "ea_schemas",
        "archive-schemas": "archive_schemas",
        "topology-editor-schemas": "topology_editor_schemas",
    }

    for subdir, category in subdirs.items():
        subdir_path = schema_path / subdir
        if subdir_path.exists():
            for xsd_file in subdir_path.glob("*.xsd"):
                schemas_by_category[category].append(f"{subdir}/{xsd_file.name}")

    return schemas_by_category


def filename_to_enum_name(filename: str) -> str:
    """
    Convert a schema filename to a valid Python enum name.

    Args:
        filename: Schema filename (e.g., "timeSeriesExportRun.xsd" or "pi-schemas/pi_timeseries.xsd")

    Returns:
        Valid Python identifier for enum (e.g., "TIME_SERIES_EXPORT_RUN" or "PI_TIMESERIES")
    """
    # Remove .xsd extension
    name = filename.replace(".xsd", "")

    # Extract just the filename part (remove subdirectory if present)
    if "/" in name:
        _, filename = name.split("/", 1)

    # Convert camelCase/PascalCase to UPPER_SNAKE_CASE
    # Handle common patterns
    name = re.sub(r"([a-z])([A-Z])", r"\1_\2", filename)
    name = re.sub(r"([A-Z])([A-Z][a-z])", r"\1_\2", name)

    # Convert to uppercase and replace non-alphanumeric chars with underscores
    name = re.sub(r"[^a-zA-Z0-9_]", "_", name.upper())

    # Clean up multiple underscores
    name = re.sub(r"_+", "_", name)
    name = name.strip("_")

    # Remove _XSD suffix if present (redundant since all values are XSD files)
    if name.endswith("_XSD"):
        name = name[:-4]

    return name


def generate_enum_content(schemas_by_category: Dict[str, List[str]]) -> str:
    """
    Generate the Python enum content.

    Args:
        schemas_by_category: Dictionary with categories and schema lists

    Returns:
        Python code for the FEWSSchemaOption enum
    """
    lines = [
        '"""',
        "FEWS Schema Options Enum.",
        "",
        "This module contains the FEWSSchemaOption enum that defines all available",
        "FEWS schema options for XML template generation and validation.",
        "This file is auto-generated by scripts/generate_fews_schema_options.py",
        '"""',
        "",
        "from enum import Enum",
        "",
        "",
        "class FEWSSchemaOption(str, Enum):",
        '    """Available FEWS schema options for XML template generation and validation"""',
        "",
    ]

    # Track used enum names to avoid duplicates
    used_names = set()

    # Generate main schemas first
    if schemas_by_category["main"]:
        lines.append("    # Main schemas")
        for schema in sorted(schemas_by_category["main"]):
            enum_name = filename_to_enum_name(schema)
            # Ensure unique name
            original_name = enum_name
            counter = 1
            while enum_name in used_names:
                enum_name = f"{original_name}_{counter}"
                counter += 1
            used_names.add(enum_name)
            lines.append(f'    {enum_name} = "{schema}"')
        lines.append("")

    # Generate other categories
    category_order = [
        "pi_schemas",
        "adapter_schemas",
        "kisters_schemas",
        "fp_schemas",
        "ea_schemas",
        "archive_schemas",
        "topology_editor_schemas",
    ]

    for category in category_order:
        if schemas_by_category[category]:
            # Convert category name to display name
            display_name = category.replace("_", " ").title().replace(" ", "_")
            lines.append(f"    # {display_name}")
            for schema in sorted(schemas_by_category[category]):
                enum_name = filename_to_enum_name(schema)
                # Ensure unique name - add category suffix if needed
                original_name = enum_name
                counter = 1
                while enum_name in used_names:
                    # Add category suffix for conflicts
                    category_suffix = category.replace("_", "").upper()
                    enum_name = f"{original_name}_{category_suffix}"
                    counter += 1
                used_names.add(enum_name)
                lines.append(f'    {enum_name} = "{schema}"')
            lines.append("")

    return "\n".join(lines)


def main():
    """Main function to generate the enum file."""
    try:
        # Scan schema directory
        print("Scanning schema directory...")
        schemas_by_category = scan_schema_directory()

        # Generate enum content
        print("Generating enum content...")
        enum_content = generate_enum_content(schemas_by_category)

        # Write to file - now we know the exact path since we're in scripts directory
        output_file = Path("../src/talk_with_fews/models/fews_schema_options.py")
        output_file.parent.mkdir(parents=True, exist_ok=True)

        with open(output_file, "w") as f:
            f.write(enum_content)

        # Print statistics
        total_schemas = sum(len(schemas) for schemas in schemas_by_category.values())
        print(f"Generated FEWSSchemaOption enum with {total_schemas} schema options:")
        for category, schemas in schemas_by_category.items():
            if schemas:
                print(f"  {category}: {len(schemas)} schemas")

        print(f"\nEnum file written to: {output_file}")

    except Exception as e:
        print(f"Error generating enum: {e}")
        return 1

    return 0


if __name__ == "__main__":
    exit(main())
